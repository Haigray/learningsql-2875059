#!/usr/bin/env node
// Inlines every validated pack into a JS module the mobile app imports directly.
//
// Bundling rather than fetching is deliberate: the app must work on a plane and
// in an immigration queue, so it ships with content and treats the network as an
// upgrade. Generated, never hand-edited — the packs stay the single source of truth.
//
// Usage: node build/bundle-packs.mjs

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';

const OUT = 'app/mobile/src/data/packs.generated.js';
const packs = readdirSync('content')
  .map(c => JSON.parse(readFileSync(`content/${c}/pack.json`, 'utf8')))
  .sort((a, b) => a.meta.country.localeCompare(b.meta.country));

const manifest = packs.map(p => ({
  code: p.meta.countryCode, country: p.meta.country,
  version: p.meta.version, verifiedAsOf: p.meta.verifiedAsOf, reviewDue: p.meta.reviewDue,
}));

mkdirSync('app/mobile/src/data', { recursive: true });
writeFileSync(OUT,
`// GENERATED by build/bundle-packs.mjs — do not edit.
// Bundled ${new Date().toISOString().slice(0, 10)} from content/*/pack.json
//
// The app ships with this content so it works with no network at all. Pack
// updates arrive as a new build; each plan pins the version it was created
// against, so an update is never a silent mutation of someone's schedule.

export const PACKS = ${JSON.stringify(packs)};

export const MANIFEST = ${JSON.stringify(manifest, null, 2)};

export const byCode = code => PACKS.find(p => p.meta.countryCode === code);
export const byCountry = name => PACKS.find(p => p.meta.country === name);
`, 'utf8');

const PROFILES_OUT = 'app/mobile/src/data/profiles.js';
const profiles = readdirSync('app/profiles')
  .filter(f => f.endsWith('.json'))
  .map(f => JSON.parse(readFileSync(`app/profiles/${f}`, 'utf8')));
writeFileSync(PROFILES_OUT,
`// GENERATED by build/bundle-packs.mjs — do not edit.
// Example mover profiles, shared with the web comparison product.
export default ${JSON.stringify(profiles, null, 2)};
`, 'utf8');

const kb = (readFileSync(OUT, 'utf8').length / 1024).toFixed(0);
console.log(`Bundled ${packs.length} packs -> ${OUT} (${kb} KB)`);
console.log(`Bundled ${profiles.length} profiles -> ${PROFILES_OUT}`);
for (const m of manifest) console.log(`  ${m.code} ${m.country} v${m.version} (verified ${m.verifiedAsOf})`);
