#!/usr/bin/env node
// Bundles everything the mobile app ships with: the packs, the example profiles,
// and the engines themselves.
//
// Bundling rather than fetching is deliberate: the app must work on a plane and
// in an immigration queue, so it ships with content and treats the network as an
// upgrade. Generated, never hand-edited — the packs stay the single source of truth.
//
// Usage: node build/bundle-app.mjs

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';

const OUT = 'app/mobile/src/data/packs.generated.js';
const packs = readdirSync('content')
  .map(c => JSON.parse(readFileSync(`content/${c}/pack.json`, 'utf8')))
  .sort((a, b) => a.meta.country.localeCompare(b.meta.country));

const manifest = packs.map(p => ({
  code: p.meta.countryCode, country: p.meta.country,
  version: p.meta.version, verifiedAsOf: p.meta.verifiedAsOf, reviewDue: p.meta.reviewDue,
}));

mkdirSync('app/mobile/src/data', { recursive: true });
writeFileSync(OUT,
`// GENERATED by build/bundle-app.mjs — do not edit.
// Bundled ${new Date().toISOString().slice(0, 10)} from content/*/pack.json
//
// The app ships with this content so it works with no network at all. Pack
// updates arrive as a new build; each plan pins the version it was created
// against, so an update is never a silent mutation of someone's schedule.

export const PACKS = ${JSON.stringify(packs)};

export const MANIFEST = ${JSON.stringify(manifest, null, 2)};

export const byCode = code => PACKS.find(p => p.meta.countryCode === code);
export const byCountry = name => PACKS.find(p => p.meta.country === name);
`, 'utf8');

const PROFILES_OUT = 'app/mobile/src/data/profiles.js';
const profiles = readdirSync('app/profiles')
  .filter(f => f.endsWith('.json'))
  .map(f => JSON.parse(readFileSync(`app/profiles/${f}`, 'utf8')));
writeFileSync(PROFILES_OUT,
`// GENERATED by build/bundle-app.mjs — do not edit.
// Example mover profiles, shared with the web comparison product.
export default ${JSON.stringify(profiles, null, 2)};
`, 'utf8');

/* --- the engines ---------------------------------------------------------
   Copied in rather than imported across the project root. Metro can be made to
   watch above its root, but that is fragile and cannot be verified without a
   device; a generated copy makes `npm install && npm start` work on a default
   Expo config. The copy is byte-checked against the source by the test suite,
   so it cannot drift. */
const ENGINE_DIR = 'app/mobile/src/engine';
mkdirSync(ENGINE_DIR, { recursive: true });

const profileFields = Object.keys(
  JSON.parse(readFileSync('schema/profile.schema.json', 'utf8')).properties);

const banner = src =>
  `// GENERATED by build/bundle-app.mjs from app/engine/${src} — do not edit.\n` +
  `// Copied rather than imported so Metro needs no cross-root configuration.\n\n`;

// plan.mjs is pure already and travels verbatim.
writeFileSync(`${ENGINE_DIR}/plan.generated.mjs`,
  banner('plan.mjs') + readFileSync('app/engine/plan.mjs', 'utf8'), 'utf8');

// match.mjs reads the profile schema off disk; inline it for the device.
const match = readFileSync('app/engine/match.mjs', 'utf8')
  .replace(/^import[^\n]*node:fs[^\n]*\n/m, '')
  .replace(/export const PROFILE_FIELDS = new Set\([\s\S]*?\);/,
    `export const PROFILE_FIELDS = new Set(${JSON.stringify(profileFields)});`);
writeFileSync(`${ENGINE_DIR}/match.generated.mjs`, banner('match.mjs') + match, 'utf8');

const compare = readFileSync('app/engine/compare.mjs', 'utf8')
  .replace("from './match.mjs'", "from './match.generated.mjs'");
writeFileSync(`${ENGINE_DIR}/compare.generated.mjs`, banner('compare.mjs') + compare, 'utf8');

for (const f of ['plan', 'match', 'compare']) {
  const src = readFileSync(`${ENGINE_DIR}/${f}.generated.mjs`, 'utf8');
  if (/node:fs|readFileSync|process\./.test(src)) {
    console.error(`refusing to bundle: ${f}.generated.mjs still contains Node-only code`);
    process.exit(1);
  }
}

const kb = (readFileSync(OUT, 'utf8').length / 1024).toFixed(0);
console.log(`Bundled ${packs.length} packs -> ${OUT} (${kb} KB)`);
console.log(`Bundled ${profiles.length} profiles -> ${PROFILES_OUT}`);
console.log(`Bundled 3 engines -> ${ENGINE_DIR}/*.generated.mjs`);
for (const m of manifest) console.log(`  ${m.code} ${m.country} v${m.version} (verified ${m.verifiedAsOf})`);
